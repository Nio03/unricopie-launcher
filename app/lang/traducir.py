TR = re.compile(r'@tr\(\s*"((?:[^"\\]|\\.)*)"(?:\s*\|\s*"((?:[^"\\]|\\.)*)"\s*%)?')


def po(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


fuente = (APP / "ui/app.slint").read_text(encoding="utf-8")
textos = []
for m in TR.finditer(fuente):
    k = (m.group(1), m.group(2)) if m.group(2) else m.group(1)
    if k not in textos:
        textos.append(k)
faltan = [t for t in textos if t not in EN]
sobran = [t for t in EN if t not in textos]
if faltan or sobran:
    print("faltan:", faltan, "\nsobran:", sobran)
    sys.exit(1)

out = ['msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"', '"Language: en\\n"',
       '"Plural-Forms: nplurals=2; plural=(n != 1);\\n"', ""]
for t in textos:
    if isinstance(t, tuple):
        a, b = EN[t]
        out += [f"msgid {po(t[0])}", f"msgid_plural {po(t[1])}", f"msgstr[0] {po(a)}", f"msgstr[1] {po(b)}", ""]
    else:
        out += [f"msgid {po(t)}", f"msgstr {po(EN[t])}", ""]
dest = APP / "lang/en/LC_MESSAGES/unricopie.po"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"{len(textos)} textos traducidos → {dest}")
